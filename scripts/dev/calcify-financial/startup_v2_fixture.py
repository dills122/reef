#!/usr/bin/env python3
"""Regenerates contracts/calcify/finite-startup-v2.json from the v1 startup witness and the v2 binding fixture.

The v2 witness keeps run and journal exactly as v1, extends ranges to the eight v2 roles (the three new histories empty at
genesis) and adds a zeroed financeGroup. `--check` fails if the committed file differs from the regenerated bytes.
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[3] / "contracts" / "calcify"
v1 = json.loads((root / "finite-startup-v1.json").read_text())
opening = json.loads((root / "finite-binding-v2.json").read_text())
digest = json.loads((root / "finite-binding-v2-manifest.json").read_text())["digest"]
ranges = list(v1["cuts"]["ranges"]) + [
    {"role": role, "partition": 0, "beginningOffset": "0", "endOffset": "0", "readCommittedEndOffset": "0"}
    for role in ("CONTROL", "FINANCE_DECISIONS", "FINANCE_CHANGELOG")
]
witness = {
    "schema": "calcify-finite-startup-v2", "nonce": v1["nonce"], "bindingDigest": digest, "opening": opening, "run": v1["run"],
    "cuts": {
        "commandGroup": v1["cuts"]["commandGroup"], "captureSourceGroup": v1["cuts"]["captureSourceGroup"],
        "financeGroup": {"groupId": opening["financeApplicationId"], "captureNextOffset": "0", "controlNextOffset": "0"},
        "ranges": ranges,
    },
    "journal": v1["journal"],
}
encoded = json.dumps(witness, separators=(",", ":"))
target = root / "finite-startup-v2.json"
if "--check" in sys.argv:
    if target.read_text() != encoded:
        sys.exit("finite-startup-v2.json is stale; run scripts/dev/calcify-financial/startup_v2_fixture.py")
else:
    target.write_text(encoded)
