#!/usr/bin/env node
// Verifies every variable the root Compose files read from the environment is
// either documented in .env.example or listed in the baseline of known
// undocumented variables. New undocumented variables fail the check; variables
// that became documented must be dropped from the baseline.
//
//   node scripts/ci/check-env-reference.mjs            # check
//   node scripts/ci/check-env-reference.mjs --update   # rewrite the baseline
import { readFile, writeFile } from "node:fs/promises";

export const composeFiles = [
  "compose.base.yml",
  "compose.local.yml",
  "compose.calcify.yml",
  "compose.arena.yml",
  "compose.fullchain-tmpfs.yml",
];
const envExamplePath = ".env.example";
const baselinePath = "scripts/ci/env-reference-baseline.txt";

const composeRef = /(?<!\$)\$\{([A-Za-z_][A-Za-z0-9_]*)(?=[}:\-+?])/g;

export function composeVariables(text) {
  const names = new Set();
  for (const match of text.matchAll(composeRef)) names.add(match[1]);
  return names;
}

export function documentedVariables(text) {
  const names = new Set();
  for (const line of text.split("\n")) {
    const match = line.match(/^\s*#?\s*([A-Z][A-Z0-9_]*)=/);
    if (match) names.add(match[1]);
  }
  return names;
}

export function parseBaseline(text) {
  return new Set(
    text
      .split("\n")
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith("#")),
  );
}

export function compare({ referenced, documented, baseline }) {
  const undocumented = [...referenced].filter((name) => !documented.has(name)).sort();
  const added = undocumented.filter((name) => !baseline.has(name));
  const stale = [...baseline].filter((name) => !referenced.has(name) || documented.has(name)).sort();
  return { undocumented, added, stale };
}

const baselineHeader = [
  "# Compose-referenced variables that are intentionally not in .env.example yet.",
  "# Generated by: node scripts/ci/check-env-reference.mjs --update",
  "# Document a variable in .env.example, then remove it from this list.",
];

async function main() {
  const referenced = new Set();
  for (const file of composeFiles) {
    for (const name of composeVariables(await readFile(file, "utf8"))) referenced.add(name);
  }
  const documented = documentedVariables(await readFile(envExamplePath, "utf8"));
  let baselineText = "";
  try {
    baselineText = await readFile(baselinePath, "utf8");
  } catch {
    // no baseline yet
  }
  const result = compare({ referenced, documented, baseline: parseBaseline(baselineText) });

  if (process.argv.includes("--update")) {
    await writeFile(baselinePath, `${[...baselineHeader, ...result.undocumented].join("\n")}\n`);
    console.log(`env reference baseline updated (${result.undocumented.length} undocumented)`);
    return;
  }
  if (result.added.length > 0) {
    console.error(`Compose reads variables that are not documented in ${envExamplePath}:`);
    for (const name of result.added) console.error(`  ${name}`);
    console.error(`Document them in ${envExamplePath} (or run with --update to baseline them).`);
    process.exitCode = 1;
  }
  if (result.stale.length > 0) {
    console.error(`Stale entries in ${baselinePath} (documented or no longer referenced):`);
    for (const name of result.stale) console.error(`  ${name}`);
    console.error("Run: node scripts/ci/check-env-reference.mjs --update");
    process.exitCode = 1;
  }
  if (!process.exitCode) {
    console.log(
      `env reference check passed (${referenced.size} referenced, ${result.undocumented.length} baselined)`,
    );
  }
}

if (import.meta.url === new URL(process.argv[1], "file://").href) await main();
